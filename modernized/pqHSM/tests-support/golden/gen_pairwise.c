/* Phase 3 slice 4: what the legacy pair-wise check (src/fhsm_pairwise.c) returns.
 *
 *   gen_pairwise <out dir>      writes pairwise.tsv
 *
 * Every key type the module generates, under every family selector (and out-of-range ones);
 * the NULL key; and for each type a mismatched pair, under every family too: the key pair's
 * parameters with its public half (for RSA the modulus) taken from a second key, built with
 * EVP_PKEY_fromdata (a mismatched EC or X25519 key under ML_KEM reaches the shared-secret
 * compare through OpenSSL's DHKEM). The keys
 * are fresh each run; only return codes are written, which do not depend on the keys. The
 * Rust replay (selftest/tests/pairwise_golden.rs) builds the same keys the same way. */
#include "fhsm_common.h"
#include "fhsm_pairwise.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <openssl/evp.h>
#include <openssl/params.h>

static const struct { const char *name, *alg, *curve; size_t bits; int family; } KEYS[] = {
    { "RSA-2048", "RSA", NULL, 2048, FHSM_PAIRWISE_RSA },
    { "EC-P-256", "EC", "P-256", 0, FHSM_PAIRWISE_EC },
    { "EC-P-521", "EC", "P-521", 0, FHSM_PAIRWISE_EC },
    { "X25519", "X25519", NULL, 0, FHSM_PAIRWISE_ECM },
    { "X448", "X448", NULL, 0, FHSM_PAIRWISE_ECM },
    { "ED25519", "ED25519", NULL, 0, FHSM_PAIRWISE_EDDSA },
    { "ED448", "ED448", NULL, 0, FHSM_PAIRWISE_EDDSA },
    { "ML-KEM-512", "ML-KEM-512", NULL, 0, FHSM_PAIRWISE_ML_KEM },
    { "ML-KEM-768", "ML-KEM-768", NULL, 0, FHSM_PAIRWISE_ML_KEM },
    { "ML-KEM-1024", "ML-KEM-1024", NULL, 0, FHSM_PAIRWISE_ML_KEM },
    { "ML-DSA-44", "ML-DSA-44", NULL, 0, FHSM_PAIRWISE_ML_DSA },
    { "ML-DSA-65", "ML-DSA-65", NULL, 0, FHSM_PAIRWISE_ML_DSA },
    { "ML-DSA-87", "ML-DSA-87", NULL, 0, FHSM_PAIRWISE_ML_DSA },
    { "SLH-DSA-SHA2-128f", "SLH-DSA-SHA2-128f", NULL, 0, FHSM_PAIRWISE_SLH_DSA },
    { "SLH-DSA-SHAKE-256f", "SLH-DSA-SHAKE-256f", NULL, 0, FHSM_PAIRWISE_SLH_DSA },
};
static const int FAMILIES[] = { -1, 0, 1, 2, 3, 4, 5, 6, 7, 8 };

static EVP_PKEY *keygen(size_t i) {
    if (KEYS[i].curve) return EVP_PKEY_Q_keygen(NULL, NULL, KEYS[i].alg, KEYS[i].curve);
    if (KEYS[i].bits) return EVP_PKEY_Q_keygen(NULL, NULL, KEYS[i].alg, KEYS[i].bits);
    return EVP_PKEY_Q_keygen(NULL, NULL, KEYS[i].alg);
}

/* a's parameters with b's public half; NULL when fromdata refuses the pair */
static EVP_PKEY *mismatched(size_t i, EVP_PKEY *a, EVP_PKEY *b) {
    const char *swap = KEYS[i].bits ? "n" : "pub";
    OSSL_PARAM *pa = NULL, *pb = NULL, *merged = NULL;
    EVP_PKEY *out = NULL;
    EVP_PKEY_CTX *ctx = EVP_PKEY_CTX_new_from_name(NULL, KEYS[i].alg, NULL);
    if (!ctx || EVP_PKEY_todata(a, EVP_PKEY_KEYPAIR, &pa) != 1
        || EVP_PKEY_todata(b, EVP_PKEY_KEYPAIR, &pb) != 1) abort();
    OSSL_PARAM *p = OSSL_PARAM_locate(pb, swap);
    if (!p) abort();
    OSSL_PARAM one[2] = { *p, OSSL_PARAM_construct_end() };
    if (!(merged = OSSL_PARAM_merge(pa, one))) abort();
    if (EVP_PKEY_fromdata_init(ctx) != 1) abort();
    if (EVP_PKEY_fromdata(ctx, &out, EVP_PKEY_KEYPAIR, merged) != 1) out = NULL;
    OSSL_PARAM_free(merged);
    OSSL_PARAM_free(pa);
    OSSL_PARAM_free(pb);
    EVP_PKEY_CTX_free(ctx);
    return out;
}

int main(int argc, char **argv) {
    if (argc != 2) { fprintf(stderr, "usage: gen_pairwise <out dir>\n"); return 2; }
    char path[512];
    snprintf(path, sizeof path, "%s/pairwise.tsv", argv[1]);
    FILE *f = fopen(path, "w");
    if (!f) return 1;
    fprintf(f, "# Generated by tests-support/golden/gen_pairwise.c from the legacy C code. Do not edit.\n"
               "# key\tfamily\trv  (selftest/tests/pairwise_golden.rs)\n");
    fprintf(f, "null\t1\t0x%x\n", (unsigned)fhsm_pairwise_check(NULL, FHSM_PAIRWISE_RSA));
    for (size_t i = 0; i < sizeof KEYS / sizeof KEYS[0]; ++i) {
        EVP_PKEY *a = keygen(i), *b = keygen(i);
        if (!a || !b) abort();
        for (size_t k = 0; k < sizeof FAMILIES / sizeof FAMILIES[0]; ++k)
            fprintf(f, "%s\t%d\t0x%x\n", KEYS[i].name, FAMILIES[k],
                    (unsigned)fhsm_pairwise_check(a, (fhsm_pairwise_family_t)FAMILIES[k]));
        EVP_PKEY *m = mismatched(i, a, b);
        for (size_t k = 0; m && k < sizeof FAMILIES / sizeof FAMILIES[0]; ++k)
            fprintf(f, "mismatched-%s\t%d\t0x%x\n", KEYS[i].name, FAMILIES[k],
                    (unsigned)fhsm_pairwise_check(m, (fhsm_pairwise_family_t)FAMILIES[k]));
        if (!m)
            fprintf(f, "mismatched-%s\t%d\trefused\n", KEYS[i].name, KEYS[i].family);
        EVP_PKEY_free(m);
        EVP_PKEY_free(a);
        EVP_PKEY_free(b);
    }
    return fclose(f) != 0;
}
