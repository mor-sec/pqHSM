#!/usr/bin/env python3
"""gen_mechs_rs.py [--check]: writes core/src/mechs/table.rs from MECHANISMS in the legacy
scripts/gen_p11_thunks.py, imported and unchanged (Q4 keeps the legacy tree as it is), so the
mechanism table keeps its one source. With --check it compares instead, and exits 1 when the
checked-in file differs (harness step 4o)."""
import importlib.util
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
OUT = HERE.parent / "core" / "src" / "mechs" / "table.rs"


def load():
    sys.dont_write_bytecode = True  # no __pycache__ left in the legacy tree
    spec = importlib.util.spec_from_file_location(
        "gen_p11_thunks", ROOT / "scripts" / "gen_p11_thunks.py")
    m = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = m  # dataclasses resolves its annotations through it
    spec.loader.exec_module(m)
    m._validate(m.MECHANISMS)
    return m.MECHANISMS


def render(mechs):
    b = lambda v: "true" if v else "false"
    lines = [
        "// @generated by modernized/pqHSM/scripts/gen_mechs_rs.py from scripts/gen_p11_thunks.py.",
        "// Do not edit: regenerate.",
        "",
        "use super::Mech;",
        "",
        "/// Sorted by value, as `src/gen/fhsm_dispatch.c`'s `fhsm_mechanism_table`.",
        "#[rustfmt::skip]",
        "pub(super) const TABLE: &[Mech] = &[",
    ]
    for m in sorted(mechs, key=lambda m: m.value):
        lines.append(
            f'    Mech {{ ckm: 0x{m.value:08X}, family: "{m.family}", op: "{m.op}", '
            f'approved: {b(m.fips == "approved")}, '
            f'handled: {b(m.handler != "dispatch_reject_fips")} }}, // {m.name}')
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    text = render(load())
    if sys.argv[1:] not in ([], ["--check"]):
        sys.exit("usage: gen_mechs_rs.py [--check]")
    if sys.argv[1:] == ["--check"]:
        same = OUT.exists() and OUT.read_text() == text
        print(f"mechanism table: {'current' if same else 'STALE'} ({text.count('Mech {')} rows)")
        return 0 if same else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
